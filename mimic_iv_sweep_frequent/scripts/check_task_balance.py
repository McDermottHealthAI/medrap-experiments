"""Gate on per-task, per-split positive counts and rates; exit non-zero if any task is unusable.

Design principle: this is a CHECK, not a FILTER. It runs *after* label generation
and fails loudly on the labels you actually produced; it never reaches back into
task-code selection to reshape which codes get sampled. That distinction matters
for the science -- a prevalence band applied as a sampling filter is task
cherry-picking (the headline AUROC would then be computed over exactly the subset
of tasks that happened to be learnable, and would silently depend on where the
band was drawn), whereas failing the run says "this label config is broken, fix
the config" and leaves the task distribution alone.

Two severities:
  FAIL (exit 1) -- the task is unusable on that split: single-class (positive rate
    exactly 0 or 1, so AUROC is undefined and the task is dropped from
    val/auroc/mean entirely), or fewer than ``--min-positives`` positives.
    ``--min-positives`` defaults to 1, which makes FAIL mean exactly
    "single-class"; pass a real floor (e.g. ``--min-positives 50``) to also reject
    tasks that are technically two-class but far too rare for an AUROC computed on
    them to mean anything.
  OUTSIDE IDEAL BAND (informational, does not affect the exit code) -- the positive
    rate is outside [``--min-rate``, ``--max-rate``] but the task is still usable.
    Deliberately kept a warning: promoting the band to a failure would turn it into
    a de facto filter on which tasks may be reported.

What the pinned medrap version guarantees -- a single-class FAIL is only an
upstream bug under some pins:
  MedRAP@0a4a1fc (mimic_iv_sweep's pin, includes McDermottHealthAI/MedRAP#98) with
    duration_distribution="fixed": generate_tasks rejects any candidate code that
    comes up single-class on any split it was given and redraws a replacement, so
    single-class FAILs should not appear. If one does, something upstream is wrong
    -- most likely a splits mismatch (the splits generate_tasks validated against
    vs. the splits checked here), or labels generated by a pin other than the one
    in pyproject.toml. That rejection loop is only used for
    duration_distribution="fixed"; "uniform"/"log-uniform" take the unfiltered
    _select_task_codes path and carry no guarantee.
  MedRAP@164c2ef (mimic_iv_sweep_frequent's pin): no rejection logic exists at all
    -- McDermottHealthAI/MedRAP#89 removed positive-rate/count filtering by design
    and #98 had not landed yet, so generate_tasks calls _select_task_codes once and
    keeps whatever it draws. Single-class FAILs here are an expected property of
    the sampled tasks, not a broken run; they still mean the labels are unusable
    and need a different horizon or selection strategy.
  No pin guarantees anything about --min-positives or the rate band: no version of
    generate_tasks filters on prevalence.

Usage:
    python scripts/check_task_balance.py data/tasks/n8/tasks
    python scripts/check_task_balance.py data/tasks/n8/tasks --min-positives 50 --quiet
"""

import argparse
import json
from pathlib import Path
from typing import NamedTuple

import polars as pl

SPLITS = ("train", "tuning", "held_out")


class TaskStat(NamedTuple):
    """Positive-label statistics for one task on one split."""

    split: str
    index: int
    code: str
    n_rows: int
    n_pos: int
    rate: float | None


def _failure_reason(stat: TaskStat, min_positives: int) -> str | None:
    """Return why ``stat`` is unusable, or ``None`` if the task passes on that split."""
    if stat.n_rows == 0:
        return "split has no labeled subjects"
    if stat.n_pos == 0:
        return "single-class (all-negative) -- AUROC undefined"
    if stat.n_pos == stat.n_rows:
        return "single-class (all-positive) -- AUROC undefined"
    if stat.n_pos < min_positives:
        return f"only {stat.n_pos} positive(s), --min-positives is {min_positives}"
    return None


def _split_stats(path: Path, code_index: dict[str, str]) -> list[TaskStat]:
    """Read one split's label parquet and compute per-task positive counts and rates."""
    df = pl.read_parquet(path)
    task_cols = sorted(
        [c for c in df.columns if c.startswith("task_")], key=lambda c: int(c.split("_")[1])
    )
    counts = df.select([pl.col(c).sum().alias(c) for c in task_cols]).row(0, named=True)

    stats = []
    for col in task_cols:
        idx = col.split("_")[1]
        n_pos = int(counts[col] or 0)
        stats.append(
            TaskStat(
                split=path.stem,
                index=int(idx),
                code=code_index.get(idx, col),
                n_rows=len(df),
                n_pos=n_pos,
                rate=n_pos / len(df) if len(df) else None,
            )
        )
    return stats


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("tasks_dir", type=Path, help="e.g. data/tasks/n8/tasks")
    parser.add_argument(
        "--min-positives",
        type=int,
        default=1,
        help="hard floor on positive labels per task per split; below this the run FAILS "
        "(default: 1, i.e. fail only on single-class tasks)",
    )
    parser.add_argument("--min-rate", type=float, default=0.01, help="ideal-band lower bound (warning only)")
    parser.add_argument("--max-rate", type=float, default=0.5, help="ideal-band upper bound (warning only)")
    parser.add_argument("--quiet", action="store_true", help="suppress the per-task detail view")
    args = parser.parse_args()

    code_index = json.loads((args.tasks_dir / "code_index.json").read_text())
    failures: list[tuple[TaskStat, str]] = []
    off_band: list[TaskStat] = []
    checked_splits: list[str] = []

    for split in SPLITS:
        path = args.tasks_dir / f"{split}.parquet"
        if not path.exists():
            continue
        checked_splits.append(split)
        stats = _split_stats(path, code_index)

        if not args.quiet:
            print(f"\n=== {split} (n={stats[0].n_rows if stats else 0}) ===")
        for stat in stats:
            reason = _failure_reason(stat, args.min_positives)
            if reason is not None:
                failures.append((stat, reason))
                flag = f"  <-- FAIL: {reason}"
            elif stat.rate is not None and not (args.min_rate <= stat.rate <= args.max_rate):
                off_band.append(stat)
                flag = "  <-- outside ideal band"
            else:
                flag = ""
            if not args.quiet:
                rate = "n/a" if stat.rate is None else f"{stat.rate:.6f}"
                print(
                    f"  task_{stat.index:<5d} ({stat.code:40s}) "
                    f"pos={stat.n_pos:>7d}/{stat.n_rows:<7d} rate={rate:>8s}{flag}"
                )

    if not checked_splits:
        print(f"\nFAIL: no split parquets found in {args.tasks_dir} (looked for {', '.join(SPLITS)}).")
        return 1

    print()
    if failures:
        bad_codes = {stat.code for stat, _ in failures}
        print(
            f"FAIL: {len(failures)} task/split check(s) across {len(bad_codes)} task code(s) "
            f"(splits checked: {', '.join(checked_splits)}; --min-positives={args.min_positives}):"
        )
        for stat, reason in failures:
            rate = "n/a" if stat.rate is None else f"{stat.rate:.6f}"
            print(f"  task_{stat.index} [{stat.split}] pos={stat.n_pos}/{stat.n_rows} rate={rate}")
            print(f"      code : {stat.code}")
            print(f"      why  : {reason}")
        print("\nThese labels are not usable as generated. Fix the label config and regenerate --")
        print("e.g. raise horizon_days, use code_selection=most_frequent, or sample prediction")
        print("anchors over clinical events instead of the whole (birth-anchored) lifetime.")
        print("Do NOT drop the offending tasks and report the rest: that is task cherry-picking.")
        return 1

    print(
        f"PASS: all tasks have both classes and >= {args.min_positives} positive(s) on every "
        f"checked split ({', '.join(checked_splits)})."
    )

    if off_band:
        print(
            f"\n{len(off_band)} task/split(s) outside the ideal [{args.min_rate}, {args.max_rate}] "
            "rate band (warning only, exit code unaffected)"
            + ("." if args.quiet else ":")
        )
        if not args.quiet:
            for stat in sorted(off_band, key=lambda s: (s.index, SPLITS.index(s.split))):
                print(f"  task_{stat.index} [{stat.split}] rate={stat.rate:.6f}  {stat.code}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
